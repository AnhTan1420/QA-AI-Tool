/**
 * Template helper: replaces {key} with values from context object
 */
function interpolate(template: string, context: Record<string, string | number | boolean | undefined>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => {
    const val = context[key];
    return val !== undefined ? String(val) : `{${key}}`;
  });
}

